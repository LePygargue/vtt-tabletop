function iconSvg(name) {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', 'icon');
  svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = ICONS[name] || '';
  return svg;
}
/** Remplace le contenu d'un élément par une icône seule (le libellé est dans aria-label / data-tip). */
function setIcon(el, name) {
  el.textContent = '';
  el.appendChild(iconSvg(name));
  el.classList.add('icon-btn');
}
for (const el of document.querySelectorAll('[data-icon]')) {
  el.prepend(iconSvg(el.dataset.icon));
  if (!el.textContent.trim()) el.classList.add('icon-btn');
}
